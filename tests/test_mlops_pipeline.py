def test_mlflow_experiment_and_runs():
    """Verify MLflow experiment tracking records runs with proper tags and metrics."""
    os.environ["MLFLOW_ALLOW_FILE_STORE"] = "true"
    os.environ["MLFLOW_DISABLE_AGENT_HINT"] = "1"
    tracking_dir = os.path.join(_project_root, "mlruns")
    assert os.path.exists(tracking_dir), f"MLflow tracking directory not found at {tracking_dir}"

    mlflow.set_tracking_uri(f"file:///{tracking_dir.replace(os.sep, '/')}")
    experiment = mlflow.get_experiment_by_name("technical_skill_mastery_baselines")
    assert experiment is not None, "MLflow experiment 'technical_skill_mastery_baselines' not found"

    runs = mlflow.search_runs(experiment_ids=[experiment.experiment_id])
    assert len(runs) >= 5, f"Expected at least 5 logged baseline runs, found {len(runs)}"

    # Check metric columns exist
    assert "metrics.accuracy" in runs.columns
    assert "metrics.f1_macro" in runs.columns
    assert "metrics.f1_weighted" in runs.columns

    # Verify champion tag exists
    champion_runs = runs[runs.get("tags.is_champion") == "True"]
    assert len(champion_runs) >= 1, "No MLflow run was tagged as champion"
    champion_row = champion_runs.iloc[0]
    assert champion_row["metrics.f1_macro"] >= 0.50, "Champion F1-macro under threshold"


