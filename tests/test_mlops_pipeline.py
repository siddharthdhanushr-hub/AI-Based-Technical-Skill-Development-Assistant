import os
import json
import yaml
import pytest
import mlflow

_project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def test_dvc_yaml_specification():
    """Verify that dvc.yaml defines the required 3-stage reproducible DAG."""
    dvc_yaml_path = os.path.join(_project_root, "dvc.yaml")
    assert os.path.exists(dvc_yaml_path), f"dvc.yaml not found at {dvc_yaml_path}"

    with open(dvc_yaml_path, "r", encoding="utf-8") as f:
        spec = yaml.safe_load(f)

    assert "stages" in spec, "dvc.yaml missing 'stages' root"
    stages = spec["stages"]

    expected_stages = ["validate_data", "feature_engineering", "train_and_track"]
    for stage_name in expected_stages:
        assert stage_name in stages, f"Stage '{stage_name}' missing from dvc.yaml"
        stage = stages[stage_name]
        assert "cmd" in stage, f"Stage '{stage_name}' missing 'cmd'"
        assert "deps" in stage, f"Stage '{stage_name}' missing 'deps'"
        assert "outs" in stage, f"Stage '{stage_name}' missing 'outs'"


